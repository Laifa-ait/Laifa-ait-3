    setSecondaryButtonText: modal.setSecondaryButtonText,
    secondaryCtaLink: modal.secondaryCtaLink,
    setSecondaryCtaLink: modal.setSecondaryCtaLink,
    desktopImage: modal.desktopImage,
    setDesktopImage: modal.setDesktopImage,
    mobileImage: modal.mobileImage,
    setMobileImage: modal.setMobileImage,
    redirectType: modal.redirectType,
    setRedirectType: modal.setRedirectType,
    tagId: modal.tagId,
    setTagId: modal.setTagId,
    ctaLink: modal.ctaLink,
    setCtaLink: modal.setCtaLink,
    targetCategory: modal.targetCategory,
    setTargetCategory: modal.setTargetCategory,
    sortOrder: modal.sortOrder,
    setSortOrder: modal.setSortOrder,
    isActive: modal.isActive,
    setIsActive: modal.setIsActive,
    startDate: modal.startDate,
    setStartDate: modal.setStartDate,
    endDate: modal.endDate,
    setEndDate: modal.setEndDate,
    showCountdown: modal.showCountdown,
    setShowCountdown: modal.setShowCountdown,
    textAlign: modal.textAlign,
    setTextAlign: modal.setTextAlign,
    contentPosition: modal.contentPosition,
    setContentPosition: modal.setContentPosition,
    overlayOpacity: modal.overlayOpacity,
    setOverlayOpacity: modal.setOverlayOpacity,
    overlayColor: modal.overlayColor,
    setOverlayColor: modal.setOverlayColor,
    shadowIntensity: modal.shadowIntensity,
    setShadowIntensity: modal.setShadowIntensity,
    imageMargin: modal.imageMargin,
    setImageMargin: modal.setImageMargin,
    imageFit: modal.imageFit,
    setImageFit: modal.setImageFit,
