    handleCreateTag: crud.handleCreateTag,
    handleDeleteTag: crud.handleDeleteTag,
    handleDeleteBanner: crud.handleDeleteBanner,
    handleToggleBannerActive: crud.handleToggleBannerActive,
    handleDuplicateBanner: crud.handleDuplicateBanner,
    handleOpenAddModal: modal.handleOpenAddModal,
    handleEditBanner: modal.handleEditBanner,
    handleSaveBanner: modal.handleSaveBanner,
