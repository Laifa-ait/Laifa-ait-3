    tagName: crud.tagName,
    setTagName: crud.setTagName,
    tagSlug: crud.tagSlug,
    setTagSlug: crud.setTagSlug,
    draggedIndex: ordering.draggedIndex,
    isUploadingDesktop: modal.isUploadingDesktop,
