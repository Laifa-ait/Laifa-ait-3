    tags: crud.tags,
    allProducts: crud.allProducts,
    isLoading: crud.isLoading,
    activeTab: modal.activeTab,
    setActiveTab: modal.setActiveTab,
    selectedZone: modal.selectedZone,
    setSelectedZone: modal.setSelectedZone,
    isModalOpen: modal.isModalOpen,
    setIsModalOpen: modal.setIsModalOpen,
    isSubmitting: modal.isSubmitting,
    editingBanner: modal.editingBanner,
    title: modal.title,
    setTitle: modal.setTitle,
    titleColor: modal.titleColor,
    setTitleColor: modal.setTitleColor,
    subtitle: modal.subtitle,
    setSubtitle: modal.setSubtitle,
    subtitleColor: modal.subtitleColor,
    setSubtitleColor: modal.setSubtitleColor,
    badge: modal.badge,
    setBadge: modal.setBadge,
    badgeColor: modal.badgeColor,
    setBadgeColor: modal.setBadgeColor,
    discountLabel: modal.discountLabel,
    setDiscountLabel: modal.setDiscountLabel,
